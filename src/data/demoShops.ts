/** 1 纬度约多少米（摆放假店用；和 Geo.boundsAround 用的同一个数）。 */
export const DEMO_METERS_PER_DEGREE = 111320;

/**
 * 假店在用户位置 center 周围的坐标（安卓 DemoPlaces.placed 的公式，逐字照搬）：
 *   lat = center.lat + meters × cos(bearing) / 111320
 *   lng = center.lng + meters × sin(bearing) / (111320 × max(cos(center.lat), 0.01))
 * 距离（distanceMeters）再用 haversine 从 center 算到这个坐标（所以会和 meters 差一点点）。
 */
export function demoLocation(center: { latitude: number; longitude: number }, placement: { bearingDeg: number; meters: number }) {
  const bearing = (placement.bearingDeg * Math.PI) / 180;
  const cosLat = Math.max(Math.cos((center.latitude * Math.PI) / 180), 0.01);
  return {
    latitude: center.latitude + (placement.meters * Math.cos(bearing)) / DEMO_METERS_PER_DEGREE,
    longitude: center.longitude + (placement.meters * Math.sin(bearing)) / (DEMO_METERS_PER_DEGREE * cosLat),
  };
}

