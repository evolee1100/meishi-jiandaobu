export type StringKey = keyof typeof STRINGS;

/** 安卓 Resources.getString(id, args…) / String.format(Locale.US, …) 的等价：只支持 %n$s 和 %n$d。 */
export function formatString(template: string, ...args: ReadonlyArray<string | number>): string {
  return template.replace(/%(\d+)\$([sd])/g, (_m, index: string, kind: string) => {
    const value = args[Number(index) - 1];
    if (value === undefined) throw new Error('缺少第 ' + index + ' 个参数：' + template);
    return kind === 'd' ? String(Math.trunc(Number(value))) : String(value);
  });
}

/** 取一条文字并填参数：t('results_title_top', 3)。 */
export function t(key: StringKey, ...args: ReadonlyArray<string | number>): string {
  return formatString(STRINGS[key], ...args);
}

/** 分享出去的纯文字：去掉屏幕排版用的隐形字符（安卓 ShareText.clean）。 */
export function cleanForShare(text: string): string {
  return text.replace(/\u00A0/g, ' ').replace(/\u2060/g, '').replace(/\u200B/g, '');
}
